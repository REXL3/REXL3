//! Speculation pieces that do not need a GPU.
//!
//! - `accept`: the keyed acceptance rule. A draft is accepted exactly when it equals the keyed sample.
//! - `AcceptStats`: per-stream acceptance estimate that feeds the global row budget.
//! - `CopyDrafter`: continue the longest earlier occurrence of the context's suffix (TensorFold's
//!   copy windows: enter with >= 8 matching tokens, offer up to 7).
//! - `stats`: per-position acceptance counters and round phase timers (telemetry every budget decision is read off).
//! - `measured`: the budget's priors as measured on the GB10 and frozen (generated by `tools/gen_measured_priors.py`).
//! - `tree`: draft trees (best-first search over the selector's lattice, calibrated node probabilities, the accept walk over a tree) and
//!   `measured_tree`, the frozen calibration table behind them (generated by `tools/gen_tree_calibration.py`).
//! - `selector_walk`: CPU reference of DFlash2's candidate-path selector (from the r0b0tlab
//!   ExLlamaV3 fork's `selector_select`, itself ported from MIT z-lab/dflash), with a keyed mode.
