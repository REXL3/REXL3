        let mut d = CopyDrafter::new(3, 64);
        // committed text 1 2 3 4 5 | picks 6 7 : the suffix `4 5 6`... earlier occurrence of `3 4 5` is not ours: use a repeat of `5 6 7`
        let committed: Vec<u32> = vec![5, 6, 7, 8, 9, 1, 2, 5];
        let (m, cont) = d.propose_after(&committed, &[6, 7], 4);
        assert_eq!(m, 3);
        assert_eq!(cont, vec![8, 9, 1, 2]);
        // a continuation can end inside the extra: the earlier occurrence is close to the end of the committed text
        let committed: Vec<u32> = vec![1, 2, 3, 4, 1, 2];
        let (m, cont) = CopyDrafter::new(2, 64).propose_after(&committed, &[3], 5);
        assert_eq!(m, 3);
        assert_eq!(cont, vec![4, 1, 2, 3]);
