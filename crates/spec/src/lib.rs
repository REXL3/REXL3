/// Number of drafts accepted: the longest prefix where `drafts[i] == samples[i]`.
/// `samples[i]` is the keyed sample at the position `drafts[i]` guessed. With `a` accepted, the
/// committed tokens are `samples[..=a]` (the accepted drafts plus one sample past them).
pub fn accept(drafts: &[u32], samples: &[u32]) -> usize {
    drafts.iter().zip(samples).take_while(|(d, s)| d == s).count()
}

/// Acceptance probability per successive draft, as an exponentially weighted estimate.
/// Each proposed draft position is a Bernoulli trial until the first rejection.
#[derive(Clone, Copy, Debug)]
pub struct AcceptStats {
    hits: f64,
    trials: f64,
    decay: f64,
    prior_hits: f64,
    prior_trials: f64,
}

impl AcceptStats {
    /// `prior` acceptance with the weight of `prior_trials` trials; `decay` per update (e.g. 0.9).
    pub fn new(prior: f64, prior_trials: f64, decay: f64) -> Self {
        Self { hits: prior * prior_trials, trials: prior_trials, decay, prior_hits: prior * prior_trials, prior_trials }
    }
    /// A round in which this stream was given no drafts: nothing was measured, so the estimate forgets one step's worth of its
    /// history in favour of the prior. Without this a stream whose estimate fell low enough to be budgeted zero drafts would stay
    /// at zero for good, because only rounds that propose drafts update it (`update` ignores `proposed == 0`).
    pub fn relax(&mut self) {
        let keep = 1.0 - self.decay;
        self.hits = self.hits * self.decay + self.prior_hits * keep;
        self.trials = self.trials * self.decay + self.prior_trials * keep;
    }
    pub fn accept_rate(&self) -> f64 {
        if self.trials <= 0.0 {
            0.0
        } else {
            (self.hits / self.trials).clamp(0.0, 0.999)
        }
    }
    /// A round proposed `proposed` drafts and `accepted` of them were accepted.
    pub fn update(&mut self, proposed: usize, accepted: usize) {
        if proposed == 0 {
            return;
        }
        let trials = (accepted + usize::from(accepted < proposed)) as f64;
        self.hits = self.hits * self.decay + accepted as f64;
        self.trials = self.trials * self.decay + trials;
    }
}

/// Positions remembered per n-gram. Lookups scan the most recent `SCAN` of them, so older ones are dead weight
/// (and a repetitive sequence would otherwise grow one list without bound).
const KEEP_PER_GRAM: usize = 64;
const SCAN: usize = 32;

/// Copy-window drafter over one sequence's tokens, indexed incrementally.
#[derive(Clone, Debug)]
pub struct CopyDrafter {
    pub min_match: usize,
    pub max_draft: usize,
    /// hash of an n-gram (n = min_match) -> end positions (exclusive) where it occurred
    index: HashMap<u64, Vec<usize>>,
    indexed: usize,
}

impl Default for CopyDrafter {
    fn default() -> Self {
        Self::new(8, 7)
    }
}

fn gram_hash(g: &[u32]) -> u64 {
    let mut h = 0xcbf29ce484222325u64;
    for &t in g {
        h ^= t as u64;
        h = h.wrapping_mul(0x100000001b3);
    }
    h
}

impl CopyDrafter {
    pub fn new(min_match: usize, max_draft: usize) -> Self {
        assert!(min_match > 0);
        Self { min_match, max_draft, index: HashMap::new(), indexed: 0 }
    }

    /// Index n-grams ending at positions up to `tokens.len()`. Call after every commit.
    pub fn extend(&mut self, tokens: &[u32]) {
        let n = self.min_match;
        if tokens.len() + 1 < self.indexed {
            // the sequence got shorter: this drafter is being reused for another one
            self.index.clear();
            self.indexed = 0;
        }
        let start = self.indexed.max(n);
        for end in start..=tokens.len() {
            let ends = self.index.entry(gram_hash(&tokens[end - n..end])).or_default();
            ends.push(end);
            if ends.len() > KEEP_PER_GRAM {
                ends.drain(..ends.len() - KEEP_PER_GRAM);
            }
        }
        self.indexed = tokens.len() + 1;
    }

    /// Up to `max` tokens continuing the longest earlier match of the context's suffix.
    pub fn propose(&mut self, tokens: &[u32], max: usize) -> Vec<u32> {
        let n = self.min_match;
        let len = tokens.len();
        let max = max.min(self.max_draft);
        if len < n + 1 || max == 0 {
            return Vec::new();
        }
        self.extend(tokens);
        let key = gram_hash(&tokens[len - n..]);
        let Some(ends) = self.index.get(&key) else { return Vec::new() };
        let mut best: Option<(usize, usize)> = None; // (match length, end)
                                                     // skip the suffix's own entry first, so the scan sees SCAN real earlier occurrences
        for &end in ends.iter().rev().filter(|&&e| e < len).take(SCAN) {
            if tokens[end - n..end] != tokens[len - n..] {
                continue; // hash collision
            }
            let mut m = n;
            while m < end && m < 256 && tokens[end - 1 - m] == tokens[len - 1 - m] {
                m += 1;
            }
            if best.map(|b| m > b.0).unwrap_or(true) {
                best = Some((m, end));
            }
        }
        match best {
            Some((_, end)) => tokens[end..len.min(end + max)].to_vec(),
            None => Vec::new(),
        }
    }

    /// The copy branch of a draft tree: the continuation of the longest earlier match of the suffix of `committed` followed by `extra` (the
    /// draft's own picks, not yet committed), and the length of that match. Only `committed` is ever indexed, so the index never holds a
    /// token that was not accepted, and a match must end inside `committed`; the continuation may run on into `extra`. At most `max` tokens
    /// (this drafter's `max_draft` does not apply); empty when the context has no earlier occurrence of its last `min_match` tokens.
    pub fn propose_after(&mut self, committed: &[u32], extra: &[u32], max: usize) -> (usize, Vec<u32>) {
        let n = self.min_match;
        let len = committed.len() + extra.len();
        if len < n + 1 || max == 0 {
            return (0, Vec::new());
        }
        self.extend(committed);
        let at = |i: usize| if i < committed.len() { committed[i] } else { extra[i - committed.len()] };
        let key_tokens: Vec<u32> = (len - n..len).map(at).collect();
        let Some(ends) = self.index.get(&gram_hash(&key_tokens)) else { return (0, Vec::new()) };
        let mut best: Option<(usize, usize)> = None; // (match length, end)
        for &end in ends.iter().rev().filter(|&&e| e < committed.len()).take(SCAN) {
            if (0..n).any(|i| at(end - n + i) != key_tokens[i]) {
                continue; // hash collision
            }
            let mut m = n;
            while m < end && m < 256 && at(end - 1 - m) == at(len - 1 - m) {
                m += 1;
            }
            if best.map(|b| m > b.0).unwrap_or(true) {
                best = Some((m, end));
            }
        }
        match best {
            Some((m, end)) => (m, (end..len.min(end + max)).map(at).collect()),
            None => (0, Vec::new()),
        }
    }
}

/// How the selector walks its candidate lists.
#[derive(Clone, Copy, Debug)]
pub enum Walk {
    /// argmax at each position (the fork's temperature-0 path)
    Greedy,
    /// keyed choice with the target's sampler at each draft's own absolute position, so the draft's
    /// noise matches the target's wherever the two distributions agree
    Keyed { sampling: Sampling, first_position: u64 },
}

/// Inputs for one sequence's block of `T` draft positions.
pub struct SelectorInputs<'a> {
    /// Per position: the draft head's top-k candidate ids and their logits (`unary`).
    pub candidates: &'a [Vec<u32>],
    pub unary: &'a [Vec<f32>],
    /// Per position: the draft hidden state projected to `rank`.
    pub hidden: &'a [Vec<f32>],
    /// Row `id` of the predecessor / successor codebooks, each `rank` long.
    pub predecessor: &'a dyn Fn(u32) -> Vec<f32>,
    pub successor: &'a dyn Fn(u32) -> Vec<f32>,
}

/// Why a selector walk could not run.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum SelectorError {
    /// `candidates`, `unary` and `hidden` must hold one entry per position, and each position's candidates and
    /// unary scores must pair up one to one.
    Shape(String),
    /// A position had no candidates, or a score was NaN (Greedy and Keyed treat both the same way).
    Sampling(SamplingError),
}

impl std::fmt::Display for SelectorError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            SelectorError::Shape(m) => write!(f, "selector inputs: {m}"),
            SelectorError::Sampling(e) => write!(f, "selector scoring: {e}"),
        }
    }
}

impl std::error::Error for SelectorError {}

/// Walk one path from the verified anchor: score(c) = unary[c] + <pred[prev] * h, succ[c]>.
///
/// Mismatched shapes, an empty candidate list and NaN scores are errors in both modes: a zip over ragged
/// inputs would otherwise silently truncate, and a NaN would stick Greedy on the first candidate.
pub fn try_selector_walk(anchor: u32, x: &SelectorInputs, walk: Walk) -> Result<Vec<u32>, SelectorError> {
    let t = x.candidates.len();
    if x.unary.len() != t || x.hidden.len() != t {
        return Err(SelectorError::Shape(format!(
            "{t} candidate lists, {} unary rows, {} hidden rows",
            x.unary.len(),
            x.hidden.len()
        )));
    }
    let mut prev = anchor;
    let mut path = Vec::with_capacity(t);
    for p in 0..t {
        if x.candidates[p].len() != x.unary[p].len() {
            return Err(SelectorError::Shape(format!(
                "position {p}: {} candidates but {} unary scores",
                x.candidates[p].len(),
                x.unary[p].len()
            )));
        }
        let a = (x.predecessor)(prev);
        let h = &x.hidden[p];
        if a.len() != h.len() {
            return Err(SelectorError::Shape(format!("position {p}: predecessor rank {} but hidden rank {}", a.len(), h.len())));
        }
        let ah: Vec<f32> = a.iter().zip(h).map(|(a, h)| a * h).collect();
        let mut scores: Vec<f32> = Vec::with_capacity(x.candidates[p].len());
        for (&c, &u) in x.candidates[p].iter().zip(&x.unary[p]) {
            let b = (x.successor)(c);
            if b.len() != ah.len() {
                return Err(SelectorError::Shape(format!(
                    "position {p}: successor rank {} but hidden rank {}",
                    b.len(),
                    ah.len()
                )));
            }
            scores.push(u + b.iter().zip(&ah).map(|(b, a)| a * b).sum::<f32>());
        }
        let tok = match walk {
            // temperature 0 is true greedy in the sampler: highest score, ties to the lowest id
            Walk::Greedy => {
                let s = Sampling { temperature: 0.0, top_k: scores.len(), top_p: 1.0, min_p: 0.0, seed: 0 };
                try_choose(&scores, &x.candidates[p], 0, &s).map_err(SelectorError::Sampling)?
            }
            Walk::Keyed { sampling, first_position } => {
                let s = Sampling { top_k: scores.len(), ..sampling };
                try_choose(&scores, &x.candidates[p], first_position + p as u64, &s).map_err(SelectorError::Sampling)?
            }
        };
        path.push(tok);
        prev = tok;
    }
    Ok(path)
}

/// `try_selector_walk` for callers that treat bad inputs as a bug: panics with the error.
pub fn selector_walk(anchor: u32, x: &SelectorInputs, walk: Walk) -> Vec<u32> {
    try_selector_walk(anchor, x, walk).unwrap_or_else(|e| panic!("{e}"))
}

