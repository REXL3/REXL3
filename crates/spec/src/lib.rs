    #[test]
    fn a_stream_given_no_drafts_drifts_back_to_the_prior() {
        let mut s = AcceptStats::new(0.5, 4.0, 0.9);
        for _ in 0..40 {
            s.update(7, 0);
        }
        let low = s.accept_rate();
        assert!(low < 0.05, "{low}");
        // rounds with no drafts measure nothing (update ignores them) but must not leave the estimate where it fell
        s.update(0, 0);
        assert_eq!(s.accept_rate(), low, "update(0, _) alone changes nothing");
        let mut prev = low;
        for _ in 0..40 {
            s.relax();
            let r = s.accept_rate();
            assert!(r >= prev && r < 0.5, "monotone toward the prior from below: {prev} -> {r}");
            prev = r;
        }
        assert!(prev > 0.45, "after 40 idle rounds the estimate is back near the prior: {prev}");
        // from above it comes down to the prior too, and it never overshoots
        let mut hot = AcceptStats::new(0.5, 4.0, 0.9);
        for _ in 0..40 {
            hot.update(7, 7);
        }
        assert!(hot.accept_rate() > 0.95);
        for _ in 0..80 {
            hot.relax();
        }
        assert!((hot.accept_rate() - 0.5).abs() < 0.05, "{}", hot.accept_rate());
    }

    #[test]
    fn stats_update_with_truncated_drafts() {
        let mut s = AcceptStats::new(0.5, 4.0, 1.0);
        s.update(0, 0); // nothing proposed: no change
        assert_eq!(s.accept_rate(), 0.5);
        s.update(7, 7); // all accepted: 7 hits in 7 trials
        assert!((s.accept_rate() - 9.0 / 11.0).abs() < 1e-12);
        s.update(7, 2); // rejected at the third draft: 2 hits in 3 trials
        assert!((s.accept_rate() - 11.0 / 14.0).abs() < 1e-12);
    }
